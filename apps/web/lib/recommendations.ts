/** The status filter's "every status" token, and the default. */
export const ALL_STATUSES = "all";
/**
 * The recommendations screen is a MONITORING list, not an approval queue
 * (ADR-0018 §5: "The UI stops being an inbox"). It therefore opens on every
 * status rather than on `awaiting_approval`, which is now an exception state.
 */
export const DEFAULT_STATUS_FILTER: StatusFilter = ALL_STATUSES;
export const PAGE_PLANS_LIMIT = 10;

export type StatusFilter = LinkPlanStatus | typeof ALL_STATUSES;

/** `status`: a contract status, or (absent/invalid) the default, every status. */
export function parseStatusFilter(params: SearchParams, name = "status"): StatusFilter {
  const value = firstParam(params, name);
  if (value === ALL_STATUSES) return ALL_STATUSES;
  return value !== undefined && (LINK_PLAN_STATUSES as readonly string[]).includes(value)
    ? (value as LinkPlanStatus)
    : DEFAULT_STATUS_FILTER;
}

/** A parsed optional parameter: its value, the raw text when it was rejected, or nothing. */
export type ParsedParam<T> =
  | { readonly kind: "absent" }
  | { readonly kind: "ok"; readonly value: T; readonly raw: string }
  | { readonly kind: "invalid"; readonly raw: string };

const MIN_SCORE = /^(?:0(?:\.\d{1,6})?|\.\d{1,6}|1(?:\.0{1,6})?)$/;

/** `min_score` in [0, 1] (the contract's bounds). Anything else is reported invalid and not sent. */
export function parseMinScore(params: SearchParams, name = "min_score"): ParsedParam<number> {
  const raw = firstParam(params, name);
  if (raw === undefined) return { kind: "absent" };
  if (!MIN_SCORE.test(raw)) return { kind: "invalid", raw: raw.slice(0, 40) };
  return { kind: "ok", value: Number.parseFloat(raw), raw };
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(value: string): boolean {
  return UUID.test(value);
}

/** A UUID filter (page id, run id). Anything else is reported invalid and not sent. */
export function parseUuidParam(params: SearchParams, name: string): ParsedParam<string> {
  const raw = firstParam(params, name);
  if (raw === undefined) return { kind: "absent" };
  return isUuid(raw) ? { kind: "ok", value: raw.toLowerCase(), raw } : { kind: "invalid", raw: raw.slice(0, 80) };
}

/** The value of a parsed parameter, or `undefined`. */
export function paramValue<T>(parsed: ParsedParam<T>): T | undefined {
  return parsed.kind === "ok" ? parsed.value : undefined;
}

/** The text to keep in a form field: the accepted or the rejected input. */
export function paramText<T>(parsed: ParsedParam<T>): string | undefined {
  return parsed.kind === "absent" ? undefined : parsed.raw;
}

export type OutcomeFilter = "kept" | "rejected";
export const OUTCOME_FILTERS: readonly OutcomeFilter[] = ["kept", "rejected"];

/** Candidate outcome filter → the contract's `rejected` boolean (`undefined` = both). */
export function outcomeToRejected(outcome: OutcomeFilter | undefined): boolean | undefined {
  return outcome === undefined ? undefined : outcome === "rejected";
}
