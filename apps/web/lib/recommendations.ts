// ---------------------------------------------------------------------------

export interface ActorPresentation {
  readonly kind: "user" | "agent" | "system" | "unknown";
  readonly label: string;
  /** The identifier after the prefix, or the whole actor when unrecognised. */
  readonly id: string;
}

const ACTOR_KIND_LABEL = { user: "User", agent: "Agent", system: "System" } as const;

export function describeActor(actor: string): ActorPresentation {
  const colon = actor.indexOf(":");
  const prefix = colon === -1 ? "" : actor.slice(0, colon);
  const id = colon === -1 ? "" : actor.slice(colon + 1);
  if ((prefix === "user" || prefix === "agent" || prefix === "system") && id !== "") {
    return { kind: prefix, label: ACTOR_KIND_LABEL[prefix], id };
  }
  return { kind: "unknown", label: "Unrecognised actor", id: actor };
}

