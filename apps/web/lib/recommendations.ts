/** Statuses in lifecycle order (the contract's order). */
export const LINK_PLAN_STATUSES = Object.keys(LINK_PLAN_STATUS) as readonly LinkPlanStatus[];

export function describeLinkPlanStatus(value: string): StatusPresentation {
  if (hasOwn(LINK_PLAN_STATUS, value)) return LINK_PLAN_STATUS[value];
  return {
    label: unknownLabel(value),
    description: "The API reported a recommendation status this console does not recognise.",
    tone: "neutral",
    known: false,
  };
}

/** Status counts in lifecycle order; statuses this build does not know come last, by key. */
export function sortStatusCounts(counts: Readonly<Record<string, number>>): { key: string; count: number }[] {
  const rank = (key: string) => {
    const index = (LINK_PLAN_STATUSES as readonly string[]).indexOf(key);
    return index === -1 ? LINK_PLAN_STATUSES.length : index;
  };
  return Object.entries(counts)
    .map(([key, count]) => ({ key, count }))
    .sort((a, b) => rank(a.key) - rank(b.key) || a.key.localeCompare(b.key, "en"));
}

