export interface NamedValue {
  readonly label: string;
  readonly description: string | null;
  readonly known: boolean;
}

function named(table: Readonly<Record<string, { label: string; description: string }>>, name: string): NamedValue {
  const entry = hasOwn(table, name) ? table[name] : undefined;
  return entry === undefined
    ? { label: humanizeKey(name), description: null, known: false }
    : { label: entry.label, description: entry.description, known: true };
}

export const describeScoreComponent = (name: string) => named(SCORE_COMPONENT, name);
export const describeScoreFactor = (name: string) => named(SCORE_FACTOR, name);

/** Tolerance for re-checking the score identities from the record (floating-point sums). */
export const SCORE_TOLERANCE = 1e-6;

export interface ScoreCheck {
  /** Σ contribution, recomputed here. */
  readonly sumOfContributions: number;
  /** Π factors, recomputed here (1 when there are none). */
  readonly productOfFactors: number;
  /** relevance == Σ contributions. */
  readonly relevanceHolds: boolean;
  /** total == relevance × Π factors. */
  readonly totalHolds: boolean;
}

/** Re-check ADR-0011 §4 from the record alone: relevance = Σ contributions; total = relevance × Π factors. */
export function checkScore(score: ScoreBreakdown): ScoreCheck {
  const sumOfContributions = score.components.reduce((sum, component) => sum + component.contribution, 0);
  const productOfFactors = Object.values(score.factors).reduce((product, factor) => product * factor, 1);
  return {
    sumOfContributions,
    productOfFactors,
    relevanceHolds: Math.abs(sumOfContributions - score.relevance) <= SCORE_TOLERANCE,
    totalHolds: Math.abs(score.relevance * productOfFactors - score.total) <= SCORE_TOLERANCE,
  };
}

export interface ConfidencePresentation {
  /** The number, to three decimals. */
  readonly value: string;
  readonly calibrated: boolean;
  /** Short visible qualifier: `"raw"` or `"calibrated"`. */
  readonly qualifier: "raw" | "calibrated";
  /** Full sentence for a title or screen reader. */
  readonly description: string;
}

/**
 * Confidence with an explicit calibration qualifier. A plan without a
 * `calibration_version` carries RAW confidence (the score itself): it is always
 * labelled "raw" and never presented as calibrated (ADR-0011 §4).
 */
export function describeConfidence(plan: Pick<LinkPlan, "confidence" | "calibration_version">): ConfidencePresentation {
  const version = plan.calibration_version?.trim() ?? "";
  if (version === "") {
    return {
      value: formatScore(plan.confidence),
      calibrated: false,
      qualifier: "raw",
      description: "Raw confidence: the uncalibrated score. It is not a probability.",
    };
  }
  return {
    value: formatScore(plan.confidence),
    calibrated: true,
    qualifier: "calibrated",
    description: `Calibrated confidence (calibration ${version}).`,
  };
}

// ---------------------------------------------------------------------------
// Placement text (always rendered as text; the anchor is highlighted with <mark>)
// ---------------------------------------------------------------------------

export interface HighlightParts {
  readonly before: string;
  readonly match: string;
  readonly after: string;
}

/**
 * Split `text` at the locator offsets `[start, end)`, counted in Unicode code
 * points (the API's offsets are Python string indices, which are code points;
 * JavaScript indices are UTF-16 units and diverge after an astral character).
 *
 * Returns `null` unless the slice equals `expected` verbatim, so the UI never
 * highlights text that is not the anchor.
 */
export function splitHighlight(text: string, start: number, end: number, expected: string): HighlightParts | null {
  const points = Array.from(text);
  if (!Number.isSafeInteger(start) || !Number.isSafeInteger(end) || start < 0 || end <= start || end > points.length) {
    return null;
  }
  const match = points.slice(start, end).join("");
  if (match !== expected) return null;
  return { before: points.slice(0, start).join(""), match, after: points.slice(end).join("") };
}

/** Code-point length (see `splitHighlight`). */
export function codePointLength(text: string): number {
  return Array.from(text).length;
}

