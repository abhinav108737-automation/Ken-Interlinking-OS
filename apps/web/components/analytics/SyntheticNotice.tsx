import { SYNTHETIC_BADGE_LABEL, SYNTHETIC_BANNER_NOTE, SYNTHETIC_BANNER_TITLE } from "@/lib/analytics";

/**
 * The persistent banner shown on any screen whose data includes synthetic rows.
 * Demo data must never be able to pass as real (ADR-0015 sections 7 and 8), so
 * this banner is not dismissible and every synthetic row is badged as well.
 */
export function SyntheticBanner() {
  return (
    <div role="alert" className="rounded border-2 border-amber-700 bg-amber-50 p-3 text-amber-950">
      <p className="font-semibold">
        <span aria-hidden="true">! </span>
        {SYNTHETIC_BANNER_TITLE}
      </p>
      <p className="max-w-prose text-sm">{SYNTHETIC_BANNER_NOTE}</p>
    </div>
  );
}

/** The per-row / per-series marker. Rendered only when the row is synthetic. */
export function SyntheticBadge({ synthetic }: { readonly synthetic: boolean | undefined }) {
  if (synthetic !== true) return null;
  return (
    <span
      className="inline-flex items-center gap-1 rounded border border-amber-700 bg-amber-100 px-1.5 py-0.5 text-xs font-semibold text-amber-950"
      title="Generated by the local demo seed. These numbers are made up."
    >
      <span aria-hidden="true">!</span>
      {SYNTHETIC_BADGE_LABEL}
    </span>
  );
}
