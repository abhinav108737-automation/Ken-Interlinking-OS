"""Static anti-regression: pgvector is GONE, not merely unused (ADR-0017 section 2).

A removed dependency comes back by accident -- someone copies an old query, or an autogenerated
migration re-adds the type. ADR-0017 is explicit that the extension must not merely be bypassed,
so this test reads the source tree and fails the build if any of its traces reappear:

* no ``<=>`` distance operator anywhere under ``services/``;
* no ``cosine_distance`` helper;
* no ``pgvector`` import, in any import form;
* no ``CREATE EXTENSION vector`` in any migration, at any revision.

It is a source-text test on purpose: it catches the competing path BEFORE a database exists to
run it against, which is the only moment at which catching it is cheap.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SERVICES = REPO_ROOT / "services"
CONTRACTS = REPO_ROOT / "contracts" / "python"
APPS_API = REPO_ROOT / "apps" / "api"
AGENTS = REPO_ROOT / "agents"
MIGRATIONS = REPO_ROOT / "migrations" / "versions"

_SOURCE_ROOTS = (SERVICES, CONTRACTS, APPS_API, AGENTS)


def _python_files(root: Path) -> list[Path]:
    return [p for p in sorted(root.rglob("*.py")) if "__pycache__" not in p.parts]


def _code_only(source: str) -> str:
    """The source with docstrings and comments removed.

    Prose may discuss the removal -- this module does so itself. What must not survive is
    executable code, so docstrings and comments are stripped before matching rather than the
    test being loosened to tolerate them.
    """
    try:
        tree = ast.parse(source)
    except SyntaxError:  # pragma: no cover - a syntax error fails elsewhere, louder
        return source
    docstrings = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            doc = ast.get_docstring(node, clean=False)
            if doc is not None:
                docstrings.add(doc)
    stripped = source
    for doc in docstrings:
        stripped = stripped.replace(doc, "")
    return "\n".join(line.split("#", 1)[0] for line in stripped.splitlines())


ALL_SOURCES = [path for root in _SOURCE_ROOTS for path in _python_files(root)]
assert ALL_SOURCES, "no Python sources found: the test would pass vacuously"


@pytest.mark.parametrize("path", ALL_SOURCES, ids=lambda p: str(p.relative_to(REPO_ROOT)))
def test_no_pgvector_distance_operator_or_helper(path: Path) -> None:
    code = _code_only(path.read_text(encoding="utf-8"))
    assert "<=>" not in code, f"{path}: the pgvector distance operator is removed (ADR-0017)"
    assert "cosine_distance" not in code, f"{path}: SQL cosine distance is removed (ADR-0017)"


@pytest.mark.parametrize("path", ALL_SOURCES, ids=lambda p: str(p.relative_to(REPO_ROOT)))
def test_no_pgvector_import(path: Path) -> None:
    """No import of the ``pgvector`` package, in any form.

    A file that does not currently parse is checked as TEXT instead of being reported here:
    whether it is valid Python is another gate's job (ruff, mypy, the import that uses it),
    and this test should answer the question it was written to answer rather than become the
    messenger for an unrelated syntax error.
    """
    source = path.read_text(encoding="utf-8")
    try:
        tree: ast.Module | None = ast.parse(source)
    except SyntaxError:
        tree = None
    if tree is not None:
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    root = alias.name.split(".", 1)[0]
                    assert root != "pgvector", f"{path}: imports pgvector"
            elif isinstance(node, ast.ImportFrom) and node.module:
                root = node.module.split(".", 1)[0]
                assert root != "pgvector", f"{path}: imports from pgvector"
    else:
        assert not re.search(r"^\s*(import|from)\s+pgvector", source, re.MULTILINE), f"{path}"
    # importlib.import_module("pgvector...") and __import__ would evade the AST walk above.
    code = _code_only(source)
    assert not re.search(r"""import_module\(\s*["']pgvector""", code), f"{path}"
    assert not re.search(r"""__import__\(\s*["']pgvector""", code), f"{path}"


def test_no_migration_creates_the_vector_extension() -> None:
    """ADR-0017: ``CREATE EXTENSION vector`` is never issued, at any revision.

    Migration 0003 originally did; it was amended, and 0010 converts a column an earlier run
    of it left behind. Asserting over EVERY migration (not just the newest) is the point: the
    chain must be runnable on a PostgreSQL without pgvector from 0001 to head.
    """
    migrations = _python_files(MIGRATIONS)
    assert len(migrations) >= 10, "migration files not found"
    for path in migrations:
        code = _code_only(path.read_text(encoding="utf-8")).lower()
        assert "create extension" not in code or "plpgsql" in code, (
            f"{path}: no migration may create an extension except plpgsql (which is built in)"
        )
        assert not re.search(r"create\s+extension[^;'\"]*vector", code), (
            f"{path}: creates the vector extension (ADR-0017 forbids it)"
        )


def test_no_vector_column_type_survives_in_the_orm_or_a_migration() -> None:
    """The custom ``Vector`` column type is deleted, and no DDL names the type."""
    from ken_core.db import types as db_types

    assert not hasattr(db_types, "Vector")
    assert not hasattr(db_types, "format_vector")
    assert not hasattr(db_types, "parse_vector")

    for path in _python_files(MIGRATIONS):
        code = _code_only(path.read_text(encoding="utf-8"))
        # 0010 mentions the type only inside the guarded conversion DO blocks, which are the
        # one place that is allowed to: they read a legacy column and convert it away.
        if path.name.startswith("0010"):
            continue
        # The word boundary matters: ``TSVECTOR()`` is PostgreSQL full-text search, which
        # is built in, is the LEXICAL channel's index, and has nothing to do with pgvector.
        assert not re.search(r"(?<![A-Za-z_])_?Vector\(\)", code), (
            f"{path}: declares a pgvector column"
        )


def test_the_embedding_is_a_real_array_in_the_orm() -> None:
    from sqlalchemy.dialects import postgresql

    from ken_core.db.models.intelligence import PageEmbedding

    column = PageEmbedding.__table__.c.embedding
    rendered = str(column.type.compile(dialect=postgresql.dialect()))  # type: ignore[no-untyped-call]
    assert rendered == "REAL[]"
