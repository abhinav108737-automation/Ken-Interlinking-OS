def _inline(text: str) -> str:
    """Escape text and turn ``[anchor](target)`` markup into ``<a>`` elements."""
    out: list[str] = []
    pos = 0
    for match in _LINK_RE.finditer(text):
        out.append(html.escape(text[pos : match.start()], quote=False))
        anchor, target = match.group(1), match.group(2)
        href = f"{SITE}{target}" if target.startswith("/") else target
        out.append(f'<a href="{html.escape(href)}">{html.escape(anchor, quote=False)}</a>')
        pos = match.end()
    out.append(html.escape(text[pos:], quote=False))
    return "".join(out)


def _report_sections(page: Page) -> tuple[Section, ...]:
    if page.phrase is None:
        return page.sections
    scope = (
        f"This report sizes the {page.geo_label} {page.phrase} market by value for 2019 to 2024 "
        f"and forecasts it to 2030. Segmentation covers {page.segments}. It profiles leading "
        "participants, reviews regulation and identifies the investment themes that matter most "
        "for new entrants."
    )
    return (
        *page.sections,
        ("Scope of this report", (scope,)),
        ("Research methodology", (METHODOLOGY[page.methodology % len(METHODOLOGY)],)),
    )


def body_html(page: Page) -> str:
    parts = ["<main><article>", f"<h1>{html.escape(page.title, quote=False)}</h1>"]
    parts.extend(f"<p>{_inline(p)}</p>" for p in page.intro)
    for heading, paragraphs in _report_sections(page):
        parts.append(f"<h2>{html.escape(heading, quote=False)}</h2>")
        parts.extend(f"<p>{_inline(p)}</p>" for p in paragraphs)
    parts.append(page.extra_html)
    parts.append("</article></main>")
    return "".join(parts)


def _rp(slug: str) -> str:
    return f"/industry-reports/{slug}"


def _ip(slug: str) -> str:
    return f"/insights/{slug}"


