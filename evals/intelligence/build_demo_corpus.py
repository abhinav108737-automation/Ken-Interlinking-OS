ALL_PAGES: Final[tuple[Page, ...]] = (*HUBS, *REPORTS, *INSIGHTS, *CORPORATE)


def record(n: int, page: Page) -> dict[str, object]:
    rec: dict[str, object] = {
        "url": f"{SITE}{page.path}",
        "external_id": f"ken-demo-{n}",
        "page_type": page.page_type,
        "title": page.title,
    }
    if page.description is not None:
        rec["meta_description"] = page.description
    rec["publication_state"] = page.state
    rec["language"] = "en"
    rec["canonical_url"] = page.canonical or f"{SITE}{page.path}"
    rec["published_at"] = page.published
    rec["modified_at"] = page.modified
    if page.metadata:
        rec["metadata"] = dict(page.metadata)
    rec["body_html"] = body_html(page)
    return rec


def render() -> str:
    paths = [p.path for p in ALL_PAGES]
    if len(paths) != len(set(paths)):
        raise SystemExit("duplicate page path in the demo corpus")
    lines = [json.dumps(HEADER, ensure_ascii=False)]
    lines.extend(
        json.dumps(record(n, page), ensure_ascii=False) for n, page in enumerate(ALL_PAGES, 1)
    )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if the committed file differs")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text("utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date; rerun without --check", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(REPO_ROOT)} is up to date ({len(ALL_PAGES)} pages)")
        return 0
    OUTPUT.write_text(text, "utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} ({len(ALL_PAGES)} pages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
